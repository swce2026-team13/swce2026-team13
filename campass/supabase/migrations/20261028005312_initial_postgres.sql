-- CAMPASS is accessed only by the Next.js server over a PostgreSQL connection.
-- The Data API roles have no grants or RLS policies on these tables.
CREATE TABLE IF NOT EXISTS public.sessions (
  id text PRIMARY KEY,
  owner text NOT NULL,
  data jsonb NOT NULL CHECK (jsonb_typeof(data) = 'object'),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.passages (
  session_id text NOT NULL REFERENCES public.sessions(id) ON DELETE CASCADE,
  waypoint_id text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (session_id, waypoint_id)
);

CREATE TABLE IF NOT EXISTS public.confusions (
  session_id text NOT NULL,
  waypoint_id text NOT NULL,
  reason text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (session_id, waypoint_id),
  FOREIGN KEY (session_id, waypoint_id)
    REFERENCES public.passages(session_id, waypoint_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.feedback (
  session_id text PRIMARY KEY REFERENCES public.sessions(id) ON DELETE CASCADE,
  data jsonb NOT NULL CHECK (jsonb_typeof(data) = 'object'),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.recognition_feedback (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data jsonb NOT NULL CHECK (jsonb_typeof(data) = 'object'),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.rate_limits (
  key text PRIMARY KEY,
  hits integer NOT NULL CHECK (hits > 0),
  expires bigint NOT NULL
);

CREATE TABLE IF NOT EXISTS public.admin_sessions (
  id text PRIMARY KEY,
  expires bigint NOT NULL
);

CREATE INDEX IF NOT EXISTS sessions_owner_idx ON public.sessions(owner);
CREATE INDEX IF NOT EXISTS passages_created_at_idx ON public.passages(created_at);
CREATE INDEX IF NOT EXISTS rate_limits_expires_idx ON public.rate_limits(expires);
CREATE INDEX IF NOT EXISTS admin_sessions_expires_idx ON public.admin_sessions(expires);

ALTER TABLE public.sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.passages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.confusions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.feedback ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.recognition_feedback ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.rate_limits ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admin_sessions ENABLE ROW LEVEL SECURITY;

-- Supabase projects can grant public-schema objects to Data API roles by default.
-- Role checks keep this migration runnable in a plain PostgreSQL CI service too.
DO $$
DECLARE api_role text;
BEGIN
  FOREACH api_role IN ARRAY ARRAY['anon', 'authenticated', 'service_role'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = api_role) THEN
      EXECUTE format(
        'REVOKE ALL ON TABLE public.sessions, public.passages, public.confusions, public.feedback, public.recognition_feedback, public.rate_limits, public.admin_sessions FROM %I',
        api_role
      );
      EXECUTE format(
        'REVOKE ALL ON SEQUENCE public.recognition_feedback_id_seq FROM %I',
        api_role
      );
    END IF;
  END LOOP;
END $$;
